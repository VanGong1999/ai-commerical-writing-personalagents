const byId = new Map(AGENT_REGISTRY.map((a) => [a.id, a]));

export function getAgent(id: string): AgentDef | undefined {
  return byId.get(id);
}

export function listAgents(format?: string): AgentDef[] {
  if (!format) return [...AGENT_REGISTRY];
  return AGENT_REGISTRY.filter(
    (a) => !a.format || a.format.includes("*") || a.format.includes(format as never),
  );
}

export function assertRegistered(agentId: string): AgentDef {
  const agent = getAgent(agentId);
  if (!agent) {
    throw new Error(`Agent not registered: ${agentId}`);
  }
  return agent;
}
